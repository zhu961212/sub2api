function account(id: number) {
  return { id, name: `Account ${id}`, platform: 'openai', type: 'oauth', schedulable: true, proxy_id: null, credentials: { plan_type: id === 1 ? 'plus' : 'pro' } }
}
function result(id = 1, overrides: Partial<AccountEvaluationResult> = {}): AccountEvaluationResult {
  return { id: `result-${id}`, kind: 'candy', model: 'test-model', effort: 'low', status: 'correct', answer: '21', duration_ms: 1200, tested_at: '2026-11-01T10:00:00Z', run: 1, runs: 1, ...overrides }
}
function history(id: number, results: AccountEvaluationResult[] = []) {
  return { ...account(id), proxy_name: null, results }
}
const stubs = {
  Pagination: true, Icon: true, AccountEvaluationAutomationSettings: true,
  EvaluationSvgPreview: defineComponent({ name: 'EvaluationSvgPreview', props: ['svg', 'alt'], template: '<div data-testid="svg-preview" />' })
}
const mountView = () => mount(AccountEvaluationView, { global: { stubs } })
function holdEvaluations() {
  const pending: { id: number; resolve: () => void; signal: AbortSignal }[] = []
  evaluateAccount.mockImplementation((id: number, _request: AccountEvaluationRequest, _emit: (event: AccountEvaluationEvent) => void, signal: AbortSignal) => new Promise<void>((resolve, reject) => {
    pending.push({ id, resolve, signal })
    signal.addEventListener('abort', () => reject(new DOMException('Aborted', 'AbortError')), { once: true })
  }))
  return pending
}

